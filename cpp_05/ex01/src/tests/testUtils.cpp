#include <iostream>

void	printHeader(const std::string& title, int headerType)
{
	if (headerType == 0)
	{
		std::cout << "========================================\n";
		std::cout << "===" << title << '\n';
		std::cout << "========================================\n";
	}
	else
	{
		std::cout << "------------------------------\n";
		std::cout << "---" << title << '\n';
		std::cout << "------------------------------\n";
	}
}

